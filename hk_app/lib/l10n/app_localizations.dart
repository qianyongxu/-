  String translate(String key) {
    String? value;
    // 1. Try full locale code first (e.g. zh_TW)
    if (_localizedValues.containsKey(locale.toString())) {
      value = _localizedValues[locale.toString()]?[key];
    }
    // 2. Fallback to language code (e.g. zh)
    if (value == null && _localizedValues.containsKey(locale.languageCode)) {
      value = _localizedValues[locale.languageCode]?[key];
    }
    // 3. Fallback to English
    if (value == null) {
      value = _localizedValues['en']?[key];
    }
    return value ?? key;
  }
